#!/usr/bin/env python3
import os
import sqlite3
import sys
from datetime import datetime, timezone
from pathlib import Path
import pandas as pd

# DB Path
DB_URL = os.environ.get("DB_URL", "user_data/tradesv3.sqlite")

def get_db_connection():
    if not Path(DB_URL).exists():
        print(f"Database not found at {DB_URL}")
        sys.exit(1)
    return sqlite3.connect(DB_URL)

def generate_report():
    conn = get_db_connection()

    # Get trades closed in last 24h
    query = """
    SELECT * FROM trades
    WHERE close_date >= datetime('now', '-1 day')
    AND is_open = 0
    """

    try:
        df = pd.read_sql_query(query, conn)
    except Exception as e:
        print(f"Error querying DB: {e}")
        conn.close()
        sys.exit(1)

    conn.close()

    date_str = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    report_file = f"user_data/reports/daily_summary_{date_str}.md"

    # Ensure dir exists
    Path("user_data/reports").mkdir(parents=True, exist_ok=True)

    with Path(report_file).open("w") as f:
        f.write(f"# Daily Trading Report ({date_str})\n\n")

        if df.empty:
            f.write("No closed trades in the last 24 hours.\n")
            print(f"Report written to {report_file} (Empty)")
            return

        # Metrics
        total_trades = len(df)

        # Win Rate
        wins = df[df["close_profit"] > 0]
        win_rate = (len(wins) / total_trades) * 100

        # Avg Return
        avg_return = df["close_profit"].mean() * 100

        # Total Profit (Absolute)
        total_profit_abs = df["close_profit_abs"].sum()

        # Exposure Time
        # open_date to close_date
        df["open_date"] = pd.to_datetime(df["open_date"])
        df["close_date"] = pd.to_datetime(df["close_date"])
        df["duration"] = (df["close_date"] - df["open_date"]).dt.total_seconds() / 60 # minutes
        avg_duration = df["duration"].mean()

        f.write("## Summary\n")
        f.write(f"- **Total Trades**: {total_trades}\n")
        f.write(f"- **Win Rate**: {win_rate:.2f}%\n")
        f.write(f"- **Avg Return**: {avg_return:.2f}%\n")
        f.write(f"- **Total Profit**: {total_profit_abs:.4f}\n")
        f.write(f"- **Avg Duration**: {avg_duration:.1f} min\n\n")

        f.write("## Top Pairs\n")
        top_pairs = df["pair"].value_counts().head(5)
        for pair, count in top_pairs.items():
            # Calculate profit per pair
            pair_profit = df[df["pair"] == pair]["close_profit_abs"].sum()
            f.write(f"- {pair}: {count} trades (PnL: {pair_profit:.2f})\n")
        f.write("\n")

        f.write("## Exit Reasons\n")
        if "exit_reason" in df.columns:
            top_reasons = df["exit_reason"].value_counts().head(5)
            for reason, count in top_reasons.items():
                f.write(f"- {reason}: {count}\n")
        else:
             # Older freqtrade versions might use sell_reason
             if "sell_reason" in df.columns:
                top_reasons = df["sell_reason"].value_counts().head(5)
                for reason, count in top_reasons.items():
                    f.write(f"- {reason}: {count}\n")

        f.write("\n_Generated by Daily Report Tool_")

    print(f"Report written to {report_file}")

if __name__ == "__main__":
    generate_report()
